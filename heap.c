#include "DS.h"

/* Зөвхөн энэ файл дотор ашиглах туслах функцүүд */
static void swim(Heap *p, int k);
static void sink(Heap *p, int k);

/*
 * b нь a-аас илүү чухал бол 1, бусад үед 0 буцаана.
 * 1. priority бага зурвас илүү чухал.
 * 2. priority тэнцвэл time бага буюу түрүүлж орсон нь чухал.
 */
int less(const Msg *a, const Msg *b)
{
    if (a->priority != b->priority)
        return a->priority > b->priority;

    return a->time > b->time;
}

/*
 * Heap-д шинэ зурвас оруулна.
 * Массивын индекс 0-ээс эхэлнэ.
 * Нөхцөл: массивт сул зай байх ёстой.
 */
void insert(Heap *p, const Msg x)
{
    /* Одоогийн урт нь шинэ элемент орох индекс болно. */
    int k = p->h_len;

    /* Шинэ зурвасыг төгсгөлд хадгална. */
    p->h_arr[k] = x;

    /* Элементийн тоог нэгээр нэмнэ. */
    p->h_len++;

    /* Шинэ зурвасыг дээш шилжүүлж зөв байрлалд оруулна. */
    swim(p, k);
}

/*
 * k индекстэй элементийг шаардлагатай бол дээш шилжүүлнэ.
 * Хүүхэд эцгээсээ илүү чухал байвал байрыг нь солино.
 */
static void swim(Heap *p, int k)
{
    /* k == 0 бол оройд хүрсэн тул зогсоно. */
    while (k > 0) {
        /* 0-ээс эхэлсэн массивт эцгийн индекс */
        int parent = (k - 1) / 2;

        /* Эцэг нь хүүхдээсээ бага чухал биш бол байрлал зөв. */
        if (!less(&p->h_arr[parent], &p->h_arr[k]))
            break;

        /* Эцэг болон хүүхдийн зурвасыг солино. */
        Msg tmp = p->h_arr[parent];
        p->h_arr[parent] = p->h_arr[k];
        p->h_arr[k] = tmp;

        /* Эцгийн байрлалаас дээш үргэлжлүүлэн шалгана. */
        k = parent;
    }
}

/*
 * k индекстэй элементийг шаардлагатай бол доош шилжүүлнэ.
 * Хүүхдүүдээс илүү чухлыг сонгож харьцуулна.
 */
static void sink(Heap *p, int k)
{
    /* Зүүн хүүхэд байгаа хугацаанд давтана. */
    while (2 * k + 1 < p->h_len) {
        int child = 2 * k + 1;  /* Зүүн хүүхдийн индекс */
        int right = child + 1; /* Баруун хүүхдийн индекс */

        /*
         * Баруун хүүхэд байгаа бөгөөд зүүнээсээ илүү
         * чухал бол баруун хүүхдийг сонгоно.
         */
        if (right < p->h_len &&
            less(&p->h_arr[child], &p->h_arr[right])) {
            child = right;
        }

        /*
         * Эцэг нь сонгосон хүүхдээс бага чухал биш бол
         * heap-ийн дараалал зөв тул зогсоно.
         */
        if (!less(&p->h_arr[k], &p->h_arr[child]))
            break;

        /* Эцгийг илүү чухал хүүхэдтэй нь солино. */
        Msg tmp = p->h_arr[k];
        p->h_arr[k] = p->h_arr[child];
        p->h_arr[child] = tmp;

        /* Хүүхдийн байрлалаас доош үргэлжлүүлэн шалгана. */
        k = child;
    }
}

/*
 * Хамгийн чухал зурвасыг heap-ээс гаргаж буцаана.
 * Хамгийн чухал зурвас h_arr[0] буюу оройд байна.
 * Нөхцөл: heap хоосон биш байх ёстой.
 */
Msg delMin(Heap *p)
{
    /* Буцаах зурвасыг түр хадгална. */
    Msg result = p->h_arr[0];

    /* Элементийн тоог нэгээр бууруулна. */
    p->h_len--;

    /* Үлдсэн элемент байгаа бол heap-ийг сэргээнэ. */
    if (p->h_len > 0) {
        /*
         * Уртыг бууруулсан тул h_len нь хуучин
         * сүүлийн элементийн индекс болж байна.
         * Тэр элементийг оройд тавина.
         */
        p->h_arr[0] = p->h_arr[p->h_len];

        /* Оройн элементийг зөв байрлал хүртэл доошлуулна. */
        sink(p, 0);
    }

    return result;
}