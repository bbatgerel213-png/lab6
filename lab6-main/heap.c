#include "DS.h"

static void swim(Heap *p, int);
static void sink(Heap *p, int);

/*
  Хоёр зурвасын чухлыг харьцуулах функц.
  b нь илүү чухал бол 1, бусад үед 0-ыг буцаах функц.
  Өөрөөр хэлбэл a < b үйлдэл юм.
*/
int less(const Msg *a, const Msg *b)
{
        // Зэрэглэл бага бол илүү чухал
        return a->priority > b->priority;
}

/*
  Оруулах функц. heap зарчмаар чухлын дарааллыг баримтлан оруулна.
  Ингэхдээ хамгийн чухал зурвас heap-ын оройд хадгалагдана.
  x зурвасыг p-ын зааж буй heap бүтцэд оруулна.
 */
void insert(Heap *p, const Msg x)
{
        // 1-ээс эхэлсэн индекстэй хүснэгтэд хамгийн төгсгөлд нь нэмнэ
        p->h_len = p->h_len + 1;
        p->h_arr[p->h_len] = x;

        // Heap зарчим алдагдаж болзошгүй тул дээшээ "сэлнэ"
        swim(p, p->h_len);
}

/*
  Heap бүтцийн swim үйлдэл.
  k нь swim үйлдлийг p-ын зааж буй heap дээр эхлүүлэх индекс.
 */
static void swim(Heap *p, int k)
{
        Msg tmp;

        // Эцэг нь хүүхдээсээ бага чухал бол (өөрөөр хэлбэл хүүхэд илүү
        // чухал бол) хоёрыг нь сольж, дээшээ үргэлжлүүлнэ
        while (k > 1 && less(&p->h_arr[k / 2], &p->h_arr[k])) {
                tmp = p->h_arr[k / 2];
                p->h_arr[k / 2] = p->h_arr[k];
                p->h_arr[k] = tmp;

                k = k / 2;
        }
}

/*
  Heap бүтцийн sink үйлдэл.
  k нь sink үйлдлийг p-ын зааж буй heap дээр эхлүүлэх индекс.
 */
static void sink(Heap *p, int k)
{
        int j;
        Msg tmp;

        // Доошоо "живж" байх хугацаандаа хамгийн чухал хүүхдээ сонгон солино
        while (2 * k <= p->h_len) {
                j = 2 * k;

                // Баруун хүүхэд байгаа бөгөөд зүүнээсээ илүү чухал бол
                if (j < p->h_len && less(&p->h_arr[j], &p->h_arr[j + 1]))
                        j = j + 1;

                // Эцэг нь хамгийн чухал хүүхдээсээ чухал (эсвэл тэнцүү) бол зогсоно
                if (!less(&p->h_arr[k], &p->h_arr[j]))
                        break;

                tmp = p->h_arr[k];
                p->h_arr[k] = p->h_arr[j];
                p->h_arr[j] = tmp;

                k = j;
        }
}

/*
  p-ын зааж буй heap бүтцээс оройн элементийг гаргаад буцаах функц.
  Гаргасны дараа орой бүрийн хувьд heap зарчим хадгалах ёстой.
 */
Msg delMin(Heap *p)
{
        Msg min = p->h_arr[1];  // оройн (хамгийн чухал) зурвас

        // Сүүлийн элементийг оройд тавиад, уртыг багасгана
        p->h_arr[1] = p->h_arr[p->h_len];
        p->h_len = p->h_len - 1;

        // Оройн элементээр heap зарчмыг сэргээнэ
        if (p->h_len > 0)
                sink(p, 1);

        return min;
}

